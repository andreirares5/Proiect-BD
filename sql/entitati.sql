CREATE TABLE Turisti
( TuristID INT IDENTITY(1,1), 
  Nume NVARCHAR(50) NOT NULL,
  Prenume NVARCHAR(50) NOT NULL,
  Email NVARCHAR(60) NOT NULL,
  NrTelefon NVARCHAR(15),
  DataNasterii DATE,
  Tara NVARCHAR(50) NOT NULL DEFAULT 'Romania',
  CONSTRAINT PK_TURISTI PRIMARY KEY (TuristID),
  CONSTRAINT UQ_TURISTI UNIQUE(email),
  CONSTRAINT CK_TURISTI CHECK(DataNasterii < GETDATE())
);

CREATE TABLE Ghizi
( GhidID INT IDENTITY(1,1) NOT NULL,
  Nume NVARCHAR(50) NOT NULL,
  Prenume NVARCHAR(50) NOT NULL,
  NrTelefon NVARCHAR(15) NOT NULL,
  LimbiVorbite NVARCHAR(120) NOT NULL DEFAULT 'Romana',
  Vechime INT NOT NULL,
  CONSTRAINT PK_GHIZI PRIMARY KEY(GhidID),
  CONSTRAINT UQ_GHIZI UNIQUE(NrTelefon),
  CONSTRAINT CK_GHIZI CHECK(Vechime >= 0)
);

CREATE TABLE Localitati
(LocalitateID INT IDENTITY(1,1) NOT NULL,
 Denumire NVARCHAR(100) NOT NULL,
 Judet NVARCHAR(80) NOT NULL,
 Regiune NVARCHAR(50) NOT NULL,
 CONSTRAINT PK_LOCALITATI PRIMARY KEY(LocalitateID),
 CONSTRAINT UQ_LOCALITATI_Denumire_Judet UNIQUE (Denumire, Judet)
 );

 CREATE TABLE Mijloace_Transport
(TransportID INT IDENTITY(1,1) NOT NULL,
 Tip NVARCHAR(30) NOT NULL,
 NrInmatriculare NVARCHAR(10) NOT NULL,
 Capacitate INT NOT NULL,
 Firma NVARCHAR(50),
 CONSTRAINT PK_MIJLOC PRIMARY KEY(TransportID),
 CONSTRAINT CK_MIJLOC CHECK(Capacitate > 0),
 CONSTRAINT UQ_MIJLOC UNIQUE(NrInmatriculare)
 );

 CREATE TABLE Obiective
 (ObiectivID INT IDENTITY(1,1) NOT NULL,
  Denumire NVARCHAR(100) NOT NULL,
  Tip NVARCHAR(50) NOT NULL,
  Pret_intrare DECIMAL(8,2) NOT NULL DEFAULT 0,
  LocalitateID INT NOT NULL,
  CONSTRAINT PK_OBIECTIVE PRIMARY KEY(ObiectivID),
  CONSTRAINT CK_OBIECTIVE CHECK(Pret_intrare >= 0),
  CONSTRAINT FK_OBIECTIVE FOREIGN KEY(LocalitateID) REFERENCES Localitati(LocalitateID)
  );

  CREATE TABLE Tururi
( TurID                INT IDENTITY(1,1) NOT NULL,
  Denumire             NVARCHAR(150) NOT NULL,
  DataPlecare          DATE NOT NULL,
  DataIntoarcere       DATE NOT NULL,
  Pret                 DECIMAL(10,2) NOT NULL,
  NrLocuri             INT NOT NULL,
  GhidID               INT NOT NULL,
  TransportID          INT NOT NULL,
  LocalitatePlecareID  INT NOT NULL,
  CONSTRAINT PK_TURURI PRIMARY KEY (TurID),
  CONSTRAINT CK_TURURI_Pret CHECK (Pret > 0),
  CONSTRAINT CK_TURURI_Locuri CHECK (NrLocuri > 0),
  CONSTRAINT CK_TURURI_Date CHECK (DataIntoarcere >= DataPlecare),
  CONSTRAINT FK_TURURI_GHIZI FOREIGN KEY (GhidID) REFERENCES Ghizi(GhidID),
  CONSTRAINT FK_TURURI_TRANSPORT FOREIGN KEY (TransportID) REFERENCES Mijloace_Transport(TransportID),
  CONSTRAINT FK_TURURI_LOCALITATI FOREIGN KEY (LocalitatePlecareID) REFERENCES Localitati(LocalitateID)
);

CREATE TABLE Rezervari
( RezervareID     INT IDENTITY(1,1) NOT NULL,
  TuristID        INT NOT NULL,
  TurID           INT NOT NULL,
  DataRezervarii  DATE NOT NULL DEFAULT GETDATE(),
  NrPersoane      INT NOT NULL,
  StatusPlata     NVARCHAR(20) NOT NULL DEFAULT 'neachitat',
  CONSTRAINT PK_REZERVARI PRIMARY KEY (RezervareID),
  CONSTRAINT UQ_REZERVARI UNIQUE(TuristID, TurID),
  CONSTRAINT CK_REZERVARI_Persoane CHECK (NrPersoane > 0),
  CONSTRAINT CK_REZERVARI_Status CHECK (StatusPlata IN ('neachitat', 'avans', 'achitat')),
  CONSTRAINT FK_REZERVARI_TURISTI FOREIGN KEY (TuristID) REFERENCES Turisti(TuristID),
  CONSTRAINT FK_REZERVARI_TURURI FOREIGN KEY (TurID) REFERENCES Tururi(TurID)
);

CREATE TABLE Tururi_Obiective
( TurID       INT NOT NULL,
  ObiectivID  INT NOT NULL,
  Ziua        INT NOT NULL,
  CONSTRAINT PK_TURURI_OBIECTIVE PRIMARY KEY (TurID, ObiectivID),
  CONSTRAINT CK_TURURI_OBIECTIVE_Ziua CHECK (Ziua > 0),
  CONSTRAINT FK_TO_TURURI FOREIGN KEY (TurID) REFERENCES Tururi(TurID) ON DELETE CASCADE,
  CONSTRAINT FK_TO_OBIECTIVE FOREIGN KEY (ObiectivID) REFERENCES Obiective(ObiectivID)
);